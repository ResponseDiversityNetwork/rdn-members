#!/bin/sh
# Bundles the script files into one file to paste into Apps Script (dist/RDN-membership.gs).
# Config must come first: other files use its constants when they load.
cd "$(dirname "$0")"
mkdir -p dist
out=dist/RDN-membership.gs
echo "// RDN membership system. Generated by apps-script/build.sh on $(date -u +%Y-%m-%d) - edit the separate files, not this one." > $out
for f in Config Geo Members Setup Photos Switching Invite Automation Emails Public Admin; do
  printf '\n// ===== %s.gs =====\n' "$f" >> $out
  cat "$f.gs" >> $out
done
echo "Wrote $out ($(wc -l < $out) lines)"
